"""위기/금지 주제 키워드 상수.

명세서 「안전 정책」 에 따라 키워드 매칭으로 입력·출력 안전 가드를 수행한다.
운영자가 코드 수정 후 컨테이너 재시작으로 갱신한다 (DB 동적 로딩 미사용 결정).

매칭은 정규화(공백 제거 + 소문자) 후 substring 비교로 한다 — 한국어 활용형
("죽고 싶다" / "죽고싶다" / "죽고 싶어요") 을 어간형 한 줄로 잡기 위함.
"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# 위기 키워드 — 사용자 메시지가 LLM 에 도달하기 전 input_guard 가 매칭한다.
# 매칭 시 추론 즉시 중단, 위기 안내 카드 오버레이로 전환 (#10).
# 명세 예시: "죽고 싶", "자살", "끝내고 싶", "사라지고 싶".
# 어간형이라 활용형(다/싶어/싶다/싶어요)을 substring 으로 한 번에 잡는다.
# ---------------------------------------------------------------------------
CRISIS_KEYWORDS: tuple[str, ...] = (
    "죽고 싶",
    "죽어버리",
    "죽을래",
    "자살",
    "자해",
    "끝내고 싶",
    "사라지고 싶",
    "살 가치",
    # '살 이유 없' 은 조사 ("살 이유가 없어") 가 끼면 substring 누락되므로
    # 더 짧은 어간으로 단축. 일부 false positive 는 안전 측 보수성으로 허용.
    "살 이유",
    "목숨을 끊",
    "생을 마감",
    "극단적 선택",
    "목매",
    "투신",
    "안락사",
)


# ---------------------------------------------------------------------------
# 금지 주제 키워드 — LLM 응답 텍스트가 출력되기 전 output_guard 가 매칭한다.
# 명세 예시: "형보다 너를 더 사랑해" 류 형제·배우자 비교 표현.
# 사후 사건에 대한 적극적 의견("사위 좋은 사람이지" 류) 은 의미 수준이라
# 키워드로 정확히 잡기 어려워 시스템 프롬프트 가이드라인(#10) 에서 처리한다.
# ---------------------------------------------------------------------------
FORBIDDEN_TOPIC_KEYWORDS: tuple[str, ...] = (
    # 형제 비교
    "형보다",
    "누나보다",
    "동생보다",
    "언니보다",
    "오빠보다",
    # 배우자 비교
    "남편보다",
    "아내보다",
    "와이프보다",
    # 비교 + 우월 표현 결합 (형제/배우자 외 일반 비교에 대비)
    "보다 더 사랑",
    "보다 더 좋아",
    "보다 더 아껴",
)


def normalize(text: str) -> str:
    """매칭 비교용 정규화 — 공백 제거 + 소문자.

    한국어 활용형의 공백 변형("죽고 싶" vs "죽고싶") 까지 substring 하나로 잡기
    위함. 이 정규화는 매칭 비교용일 뿐 원본 텍스트는 호출자가 그대로 보관한다.
    """
    return text.replace(" ", "").replace("\t", "").lower()
